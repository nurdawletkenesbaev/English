// Yangi so‘z qo‘shish funksiyasi
export function addInitialWord(newWord) {
  initialWords.push({ ...newWord, id: Date.now().toString() })
}

// Barcha so‘zlarni almashtirish (copy-paste qilingan massiv uchun)
export function setInitialWords(newArray) {
  initialWords.length = 0
  newArray.forEach((w, i) => {
    initialWords.push({ ...w, id: (i + 1).toString() })
  })
}
